#!/usr/bin/env python3
"""Verify pinned firmware bytes, then embed without executing or disassembling."""
from pathlib import Path
import hashlib, json
root = Path(__file__).resolve().parent.parent
manifest = json.loads((root / 'firmware/manifest.json').read_text())
license_text = (root / 'firmware/LICENSE.Realtek').read_text()
output = ['/*\n' + license_text + '\n*/', '/* Generated by scripts/embed-firmware.py. */']
for name, record in sorted(manifest['images'].items()):
    blob = (root / 'firmware' / name).read_bytes()
    if len(blob) != record['size'] or hashlib.sha256(blob).hexdigest() != record['sha256']:
        raise SystemExit('Firmware checksum mismatch: ' + name)
    output.append('static const unsigned char ' + record['symbol'] + '[] = {')
    for offset in range(0, len(blob), 16):
        output.append('    ' + ','.join('0x%02x' % x for x in blob[offset:offset+16]) + ',')
    output.append('};')
(root / 'src/firmware/images.h').write_text('\n'.join(output) + '\n')
print('Verified and embedded two pinned Realtek firmware images.')
